from agentforge_platform.spec import SoftwareSpecification

_STRICT = ConfigDict(extra="forbid")

RELATIONS_MIGRATION_REL = "backend/src/main/resources/db/migration/V900__relations.sql"
AUTHORITATIVE_OPENAPI_REL = "backend/openapi.json"
_SQL_MIGRATION_RE = re.compile(
    r"^backend/src/main/resources/db/migration/V(\d+)__[A-Za-z0-9_.-]+\.sql$"
)
_HTTP_METHODS = frozenset({"get", "post", "put", "delete", "patch", "head", "options"})


class BackendMergeResult(BaseModel):
    """``merge_department_deliverables`` 返回的结构化总装结果。"""

    model_config = _STRICT

    ok: bool
    output_dir: str
    merged_files: list[str] = []
    relations_sql_path: str | None = None
    openapi_path: str | None = None
    openapi_doc: dict[str, Any] = {}
    openapi_sha256: str | None = None
    conflict_tickets: list[DefectTicket] = []
    manifest_hash: str | None = None


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _iter_dept_candidate_files(
    dept_staging: Path,
    base_file_set: frozenset[str],
) -> list[str]:
    """扫描部门暂存区内除只读底座、构建缓存与 ``.staging`` 外的部门自有产物路径。"""
    owned: list[str] = []
    for path in sorted(dept_staging.rglob("*")):
        if not path.is_file() or path.is_symlink():
            continue
        rel = path.relative_to(dept_staging).as_posix()
        parts = PurePosixPath(rel).parts
        if any(p in _EXCLUDED_COPY or p == STAGING_DIRNAME for p in parts):
            continue
        if rel in (API_FRAGMENT_FILENAME, READONLY_MANIFEST_NAME):
            continue
        if rel in base_file_set:
            continue
        owned.append(rel)
    return owned


def _make_contract_mismatch_ticket(
    *,
    run_id: int,
    dept_id: str,
    integration_round: int,
    summary: str,
    affected_paths: list[str],
    idx: int,
) -> DefectTicket:
    return DefectTicket(
        ticket_id=f"merge-{run_id}-{dept_id}-r{integration_round}-{idx}",
        run_id=run_id,
        phase="backend",
        dept_id=dept_id,
        scope="integration",
        round=integration_round,
        error_class="CONTRACT_MISMATCH",
        summary=summary,
        affected_paths=affected_paths,
        log_excerpt=summary,
        verifier_kind="docker_runner",
    )


def _render_relations_sql(
    *,
    blueprint: ArchitectureBlueprint,
    spec: SoftwareSpecification | None,
) -> str:
    """确定性生成跨模块关联迁移脚本 ``V900__relations.sql``（不侵占任何部门 V010..V899 号段）。"""
    lines = [
        "-- Auto-generated by AgentForge FP06 backend assembler (V900 cross-module relations).",
        f"-- Blueprint version: {blueprint.blueprint_version}, hash: {blueprint.blueprint_hash()[:16]}",
        "",
    ]
    relations = list(spec.relations) if spec is not None else []
    emitted = 0
    for idx, rel in enumerate(relations, start=1):
        if not isinstance(rel, dict):
            continue
        child_table = str(rel.get("from_table") or rel.get("child_table") or "").strip()
        child_col = str(rel.get("from_column") or rel.get("child_column") or "").strip()
        parent_table = str(rel.get("to_table") or rel.get("parent_table") or "").strip()
        parent_col = str(rel.get("to_column") or rel.get("parent_column") or "id").strip()
        if all(re.fullmatch(r"[a-z][a-z0-9_]*", x) for x in (child_table, child_col, parent_table, parent_col)):
            fk_name = f"fk_v900_{idx}_{child_table}_{parent_table}"[:60]
            lines.append(
                f"ALTER TABLE {child_table} ADD CONSTRAINT {fk_name} "
                f"FOREIGN KEY ({child_col}) REFERENCES {parent_table}({parent_col});"
            )
            emitted += 1
        else:
            desc = json.dumps(rel, ensure_ascii=False, sort_keys=True)
            lines.append(f"-- Relation metadata #{idx}: {desc}")
    if emitted == 0:
        lines.append("-- No explicit physical cross-table ALTER TABLE FK statements declared; logical cross-module references verified via Facade contracts.")
        lines.append("SELECT 1;")
    lines.append("")
    return "\n".join(lines)


def _build_merged_openapi(
    *,
    blueprint: ArchitectureBlueprint,
    spec: SoftwareSpecification | None,
    deliverables_by_dept: dict[str, DepartmentDeliverable],
    run_id: int,
    integration_round: int,
) -> tuple[dict[str, Any], list[DefectTicket]]:
    """合并各部门 ``api-fragment.json`` 与冻结蓝图 HTTP 契约，检测路由重复冲突。"""
    paths: dict[str, dict[str, Any]] = {}
    schemas: dict[str, Any] = {}
    route_owners: dict[tuple[str, str], str] = {}
    conflicts: list[DefectTicket] = []

    # 1. 合并各部门产出的 api-fragment.json
    for dept_id in sorted(deliverables_by_dept):
        deliverable = deliverables_by_dept[dept_id]
        frag = dict(deliverable.api_fragment or {})
        if not frag and deliverable.staging_dir:
            frag_file = Path(deliverable.staging_dir) / API_FRAGMENT_FILENAME
            if frag_file.is_file():
                try:
                    loaded = json.loads(frag_file.read_text(encoding="utf-8"))
                    if isinstance(loaded, dict):
                        frag = loaded
                except (OSError, ValueError):
                    frag = {}

        frag_paths = frag.get("paths")
        if isinstance(frag_paths, dict):
            for path_key, methods_obj in sorted(frag_paths.items()):
                if not isinstance(methods_obj, dict):
                    continue
                for method_raw, op_obj in sorted(methods_obj.items()):
                    method = method_raw.lower()
                    if method not in _HTTP_METHODS:
                        continue
                    route_key = (path_key, method)
                    if route_key in route_owners and route_owners[route_key] != dept_id:
                        other = route_owners[route_key]
                        summary = (
                            f"OpenAPI 路由冲突：{method.upper()} {path_key} 同时被部门 "
                            f"{other} 与 {dept_id} 声明"
                        )
                        conflicts.append(
                            _make_contract_mismatch_ticket(
                                run_id=run_id,
                                dept_id=dept_id,
                                integration_round=integration_round,
                                summary=summary,
                                affected_paths=[API_FRAGMENT_FILENAME],
                                idx=len(conflicts) + 1,
                            )
                        )
                        continue
                    route_owners[route_key] = dept_id
                    op_copy = dict(op_obj) if isinstance(op_obj, dict) else {}
                    op_copy.setdefault("x-department", dept_id)
                    paths.setdefault(path_key, {})[method] = op_copy

        frag_components = frag.get("components")
        if isinstance(frag_components, dict) and isinstance(frag_components.get("schemas"), dict):
            for schema_name, schema_def in sorted(frag_components["schemas"].items()):
                schemas[schema_name] = schema_def

    # 2. 补充冻结蓝图中声明但片段尚未写入的 HTTP 契约（确保权威 OpenAPI 零遗漏）
    for cap in sorted(blueprint.frozen_contracts, key=lambda c: c.capability_id):
        if cap.interface_kind != KIND_HTTP or not cap.http_method or not cap.http_path:
            continue
        method = cap.http_method.lower()
        route_key = (cap.http_path, method)
        if route_key not in route_owners:
            route_owners[route_key] = cap.owner_module_id
            paths.setdefault(cap.http_path, {})[method] = {
                "operationId": cap.capability_id.replace(".", "_"),
                "summary": cap.signature,
                "x-department": cap.owner_module_id,
                "x-auth": list(cap.auth_constraints),
                "responses": {
                    "200": {"description": "OK"},
                },
            }

    # 3. 补充蓝图公共 DTO Schema 定义（供 FP07 TS 类型生成直接消费）
    java_to_openapi: dict[str, tuple[str, str | None]] = {
        "String": ("string", None),
        "Long": ("integer", "int64"),
        "Integer": ("integer", "int32"),
        "Boolean": ("boolean", None),
        "BigDecimal": ("number", "decimal"),
        "Double": ("number", "double"),
        "Instant": ("string", "date-time"),
        "LocalDateTime": ("string", "date-time"),
        "LocalDate": ("string", "date"),
    }
    for dto in sorted(blueprint.shared_dtos, key=lambda d: d.name):
        if dto.name in schemas:
            continue
        props: dict[str, Any] = {}
        required_fields: list[str] = []
        for field in dto.fields:
            if field.java_type in java_to_openapi:
                oa_type, oa_fmt = java_to_openapi[field.java_type]
                prop: dict[str, Any] = {"type": oa_type}
                if oa_fmt:
                    prop["format"] = oa_fmt
            else:
                prop = {"$ref": f"#/components/schemas/{field.java_type}"}
            props[field.name] = prop
            if field.required:
                required_fields.append(field.name)
        schemas[dto.name] = {
            "type": "object",
            "x-owner-module": dto.owner_module_id,
            "properties": props,
            "required": required_fields,
        }

    # 补充模板基座健康检查与登录端点
    paths.setdefault(
        "/api/health",
        {
            "get": {
                "operationId": "base_health",
                "summary": "Backend health check",
                "x-department": "base",
                "x-auth": ["PUBLIC"],
                "security": [],
                "responses": {"200": {"description": "OK"}},
            }
        },
    )

    # 对齐 OpenAPI 3.0 标准 security 字段（与底座 SecurityConfig 的 JWT Bearer 鉴权保持一致）
    public_base_paths = {"/api/health", "/api/auth/login"}
    for path_key, methods_obj in paths.items():
        if not isinstance(methods_obj, dict):
            continue
        for method_key, op_obj in methods_obj.items():
            if method_key.lower() not in _HTTP_METHODS or not isinstance(op_obj, dict):
                continue
            if "security" in op_obj:
                continue
            x_auth = op_obj.get("x-auth")
            is_public = path_key in public_base_paths or (
                isinstance(x_auth, list) and "PUBLIC" in {str(a).upper() for a in x_auth}
            )
            op_obj["security"] = [] if is_public else [{"bearerAuth": []}]

    doc: dict[str, Any] = {
        "openapi": "3.0.3",
        "info": {
            "title": f"AgentForge Factory Backend ({blueprint.project_id})",
            "version": f"1.0.{blueprint.blueprint_version}",
            "description": spec.goal if spec is not None else "",
        },
        "x-agentforge-blueprint-version": blueprint.blueprint_version,
        "x-agentforge-blueprint-hash": blueprint.blueprint_hash(),
        "x-agentforge-frozen": False,
        "paths": dict(sorted(paths.items())),
        "components": {
            "schemas": dict(sorted(schemas.items())),
            "securitySchemes": {
                "bearerAuth": {
                    "type": "http",
                    "scheme": "bearer",
                    "bearerFormat": "JWT",
                }
            },
        },
    }
    return doc, conflicts


def freeze_authoritative_openapi(
    output_dir: str | Path,
    openapi_doc: dict[str, Any],
) -> tuple[Path, str, dict[str, Any]]:
    """仅在独立 Docker Runner 后端总验收全 ``PASS`` 后正式冻结权威 ``backend/openapi.json``。"""
    frozen_doc = dict(openapi_doc)
    frozen_doc["x-agentforge-frozen"] = True
    payload = (json.dumps(frozen_doc, indent=2, ensure_ascii=False, sort_keys=True) + "\n").encode(
        "utf-8"
    )
    target = Path(output_dir).resolve() / AUTHORITATIVE_OPENAPI_REL
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(payload)
    return target, _sha256_bytes(payload), frozen_doc


def merge_department_deliverables(
    base_dir: str | Path,
    deliverables: Mapping[str, DepartmentDeliverable] | Sequence[DepartmentDeliverable],
    output_dir: str | Path,
    *,
    blueprint: ArchitectureBlueprint,
    spec: SoftwareSpecification | None = None,
    run_id: int = 0,
    integration_round: int = 1,
) -> BackendMergeResult:
    """FP06：确定性总装所有通过小循环的后端部门产物，产出完整后端工程与候选 ``backend/openapi.json``。"""
    resolved_base = Path(base_dir).resolve()
    final_out = Path(output_dir).resolve()
    base_manifest: BaseManifest = load_base_manifest(resolved_base)
    base_file_set = frozenset(e.path for e in base_manifest.files)

    deliverables_by_dept: dict[str, DepartmentDeliverable] = (
        dict(deliverables)
        if isinstance(deliverables, Mapping)
        else {d.dept_id: d for d in deliverables}
    )
    modules_by_id = {m.module_id: m for m in blueprint.modules}
    tickets: list[DefectTicket] = []

    # 1. 静态跨模块契约一致性门禁（复用 F06 module_integration）
    static_issues = integration_issues(
        blueprint.to_module_registry(),
        blueprint.to_interface_registry(),
    )
    if static_issues:
        first_dept = blueprint.modules[0].module_id if blueprint.modules else "chief"
        tickets.append(
            _make_contract_mismatch_ticket(
                run_id=run_id,
                dept_id=first_dept,
                integration_round=integration_round,
                summary="跨模块静态一致性校验失败：" + "；".join(static_issues),
                affected_paths=[],
                idx=len(tickets) + 1,
            )
        )

    # 2. 逐部门检查：底座/Facade 零篡改、SQL 号段合规、跨部门零路径冲突
    file_owners: dict[str, str] = {}
    files_to_copy: list[tuple[str, Path, str]] = []  # (dept_id, src_path, rel_path)

    for dept_id in sorted(modules_by_id):
        module = modules_by_id[dept_id]
        deliverable = deliverables_by_dept.get(dept_id)
        if deliverable is None or deliverable.status != "PASSED":
            tickets.append(
                _make_contract_mismatch_ticket(
                    run_id=run_id,
                    dept_id=dept_id,
                    integration_round=integration_round,
                    summary=f"部门 {dept_id} 缺少已通过小循环的交付物（status={deliverable.status if deliverable else 'MISSING'}）",
                    affected_paths=[],
                    idx=len(tickets) + 1,
                )
            )
            continue

        dept_staging = Path(deliverable.staging_dir).resolve()
        if not dept_staging.is_dir():
            tickets.append(
                _make_contract_mismatch_ticket(
                    run_id=run_id,
                    dept_id=dept_id,
                    integration_round=integration_round,
                    summary=f"部门 {dept_id} 暂存目录不存在：{dept_staging}",
                    affected_paths=[],
                    idx=len(tickets) + 1,
                )
            )
            continue

        # 2a. 底座与 api/*Facade.java 零篡改门禁（若暂存区含底座副本则全量核验 SHA-256）
        if (dept_staging / "backend").is_dir():
            tamper_violations = verify_base_integrity(dept_staging, base_manifest)
            if tamper_violations:
                tickets.append(
                    _make_contract_mismatch_ticket(
                        run_id=run_id,
                        dept_id=dept_id,
                        integration_round=integration_round,
                        summary=f"部门 {dept_id} 篡改只读底座或跨模块 api/*Facade.java："
                        + "；".join(tamper_violations),
                        affected_paths=[],
                        idx=len(tickets) + 1,
                    )
                )
                continue

        dept_files = _iter_dept_candidate_files(dept_staging, base_file_set)

        # 2b. 禁止部门产出任何触及底座/受保护 api/ 前缀的新增文件（放行本部门专属 test_paths）
        base_path_violations = check_department_paths_against_base(
            dept_files,
            base_manifest,
            allowed_test_paths=module.test_paths,
        )
        if base_path_violations:
            tickets.append(
                _make_contract_mismatch_ticket(
                    run_id=run_id,
                    dept_id=dept_id,
                    integration_round=integration_round,
                    summary=f"部门 {dept_id} 越权写入受保护底座或 api/ 路径："
                    + "；".join(base_path_violations),
                    affected_paths=dept_files,
                    idx=len(tickets) + 1,
                )
            )
            continue

        # 2c. 校验 SQL 迁移号段严格落在本部门 migration_range 内
        for rel in dept_files:
            _validate_rel(rel)
            sql_match = _SQL_MIGRATION_RE.fullmatch(rel)
            if sql_match and module.migration_range is not None:
                ver = int(sql_match.group(1))
                lo, hi = module.migration_range
                if not (lo <= ver <= hi):
                    tickets.append(
                        _make_contract_mismatch_ticket(
                            run_id=run_id,
                            dept_id=dept_id,
                            integration_round=integration_round,
                            summary=f"部门 {dept_id} SQL 迁移 {rel} 版本号 V{ver} 越出分配号段 [{lo}..{hi}]",
                            affected_paths=[rel],
                            idx=len(tickets) + 1,
                        )
                    )
                    continue

            # 2d. 校验任意两个部门之间零路径冲突
            if rel in file_owners:
                other = file_owners[rel]
                msg = f"跨部门文件路径冲突：{rel} 同时被部门 {other} 与 {dept_id} 写入"
                tickets.append(
                    _make_contract_mismatch_ticket(
                        run_id=run_id,
                        dept_id=other,
                        integration_round=integration_round,
                        summary=msg,
                        affected_paths=[rel],
                        idx=len(tickets) + 1,
                    )
                )
                tickets.append(
                    _make_contract_mismatch_ticket(
                        run_id=run_id,
                        dept_id=dept_id,
                        integration_round=integration_round,
                        summary=msg,
                        affected_paths=[rel],
                        idx=len(tickets) + 1,
                    )
                )
                continue

            file_owners[rel] = dept_id
            files_to_copy.append((dept_id, dept_staging / rel, rel))

    # 3. 聚合 OpenAPI 并检测跨部门 HTTP 路由冲突
    openapi_doc, openapi_conflicts = _build_merged_openapi(
        blueprint=blueprint,
        spec=spec,
        deliverables_by_dept=deliverables_by_dept,
        run_id=run_id,
        integration_round=integration_round,
    )
    tickets.extend(openapi_conflicts)

    if tickets:
        return BackendMergeResult(
            ok=False,
            output_dir=str(final_out),
            conflict_tickets=tickets,
        )

    # 4. 全部门禁通过 → 在同级临时目录原子装配并替换 output_dir
    final_out.parent.mkdir(parents=True, exist_ok=True)
    tmp_dir = final_out.parent / f".{final_out.name}.tmp-{os.getpid()}-{uuid.uuid4().hex[:8]}"
    if tmp_dir.exists():
        remove_readonly_tree(tmp_dir)
    tmp_dir.mkdir(parents=True, exist_ok=True)

    try:
        shutil.copytree(resolved_base / "backend", tmp_dir / "backend")
        make_writable_tree(tmp_dir / "backend")

        for _dept_id, src, rel in files_to_copy:
            dest = (tmp_dir / rel).resolve()
            if not _is_within(tmp_dir, dest):
                raise ValueError(f"合并文件路径越界：{rel}")
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dest)

        # 自动生成 V900__relations.sql
        relations_dest = tmp_dir / RELATIONS_MIGRATION_REL
        relations_dest.parent.mkdir(parents=True, exist_ok=True)
        relations_dest.write_text(
            _render_relations_sql(blueprint=blueprint, spec=spec),
            encoding="utf-8",
        )

        # 写入候选合并 backend/openapi.json（尚未冻结，须等 Docker Runner 全 PASS 后冻结）
        openapi_bytes = (
            json.dumps(openapi_doc, indent=2, ensure_ascii=False, sort_keys=True) + "\n"
        ).encode("utf-8")
        openapi_dest = tmp_dir / AUTHORITATIVE_OPENAPI_REL
        openapi_dest.parent.mkdir(parents=True, exist_ok=True)
        openapi_dest.write_bytes(openapi_bytes)

        # 合并完成后二次核验底座与 Facade Stub 零篡改
        final_tamper = verify_base_integrity(tmp_dir, base_manifest)
        if final_tamper:
            return BackendMergeResult(
                ok=False,
                output_dir=str(final_out),
                conflict_tickets=[
                    _make_contract_mismatch_ticket(
                        run_id=run_id,
                        dept_id=blueprint.modules[0].module_id,
                        integration_round=integration_round,
                        summary="总装后底座完整性复核失败：" + "；".join(final_tamper),
                        affected_paths=[],
                        idx=1,
                    )
                ],
            )

        # 计算总装产物清单哈希
        merged_files: list[str] = []
        hasher = hashlib.sha256()
        for path in sorted(tmp_dir.rglob("*")):
            if not path.is_file():
                continue
            rel = path.relative_to(tmp_dir).as_posix()
            merged_files.append(rel)
            hasher.update(rel.encode("utf-8"))
            hasher.update(b"\0")
            hasher.update(_sha256_bytes(path.read_bytes()).encode("ascii"))
            hasher.update(b"\n")

        if final_out.exists():
            remove_readonly_tree(final_out)
        os.replace(tmp_dir, final_out)

        return BackendMergeResult(
            ok=True,
            output_dir=str(final_out),
            merged_files=merged_files,
            relations_sql_path=RELATIONS_MIGRATION_REL,
            openapi_path=str(final_out / AUTHORITATIVE_OPENAPI_REL),
            openapi_doc=openapi_doc,
            openapi_sha256=_sha256_bytes(openapi_bytes),
            conflict_tickets=[],
            manifest_hash=hasher.hexdigest(),
        )
    except Exception:
        if tmp_dir.exists():
            remove_readonly_tree(tmp_dir)
        raise


