"""FP06：后端总装、跨模块冲突/篡改门禁、``V900__relations.sql`` 与权威 ``openapi.json`` 聚合（``factory_assembler.py``）。

核心职责（纯确定性执行，**0 模型调用**）：
1. 合并前严格校验：
   - 复用 ``module_integration.integration_issues()`` 执行跨模块静态一致性检查；
   - 核验每个部门暂存区对只读底座与 ``api/*Facade.java`` 签名零篡改（复用 ``factory_base_builder.verify_base_integrity``）；
   - 校验每个部门新增/修改的 Flyway SQL 迁移脚本号段严格落在本部门 ``migration_range`` 内（避开 ``V001..V009`` 与 ``V900+``）；
   - 校验任意两个部门之间零文件路径冲突与零 HTTP ``(path, method)`` 路由冲突；
   - 任一违规即拒绝合并，并产出责任部门的 ``CONTRACT_MISMATCH`` 缺陷单；
2. 校验全部通过后，原子组装完整后端目录 ``output_dir/``，确定性生成跨模块关联脚本
   ``backend/src/main/resources/db/migration/V900__relations.sql`` 与聚合后的 ``backend/openapi.json``
   （初始标记 ``x-agentforge-frozen=false``，仅在独立 Docker Runner 总验收全 ``PASS`` 后由
   ``freeze_authoritative_openapi()`` 正式冻结供前端流水线消费）。
"""

